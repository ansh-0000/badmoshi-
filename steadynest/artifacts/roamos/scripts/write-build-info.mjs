// Regenerates constants/buildInfo.ts before every `expo start`.
//
// Exists because this project briefly had two checkouts of itself on disk and
// there was no way to tell from the running app which one Metro was serving.
// The badge this feeds is dev-only, but knowing the tree/branch at a glance is
// what makes "it's still broken" reports trustworthy.

import { execSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const appRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const git = (args) => {
  try {
    return execSync(`git ${args}`, { cwd: appRoot, stdio: ['ignore', 'pipe', 'ignore'] })
      .toString()
      .trim();
  } catch {
    return null;
  }
};

// The last two path segments are enough to tell the trees apart without
// pasting an absolute Windows path into a phone-sized badge.
const shortTree = appRoot.replace(/\\/g, '/').split('/').slice(-3).join('/');

// ── Fix-presence probe ───────────────────────────────────────────────────────
// The branch name alone can lie. This tree is a merge of two checkouts and does
// not correspond to any single commit, and while the repo root is still an
// ancestor directory, `git rev-parse` reports whatever branch *that* repo is on
// rather than the one the code came from. Probing for the fixes themselves is
// the only claim that survives all of that, so the badge reports this instead.
const FIX_MARKERS = [
  ['tira chips', 'app/(tabs)/tira.tsx', 'bottomDock'],
  ['tab clearance', 'constants/layout.ts', 'useTabBarClearance'],
  ['theme tokens', 'constants/colors.ts', 'fixedInk'],
  ['segment contrast', 'constants/colors.ts', 'segmentInactive'],
  ['stays skeleton', 'app/(tabs)/index.tsx', 'StayRowSkeleton'],
];

const missing = FIX_MARKERS.filter(([, file, needle]) => {
  const p = resolve(appRoot, file);
  return !existsSync(p) || !readFileSync(p, 'utf8').includes(needle);
}).map(([label]) => label);

const info = {
  tree: shortTree,
  absPath: appRoot.replace(/\\/g, '/'),
  branch: git('rev-parse --abbrev-ref HEAD') ?? 'no-git',
  commit: git('rev-parse --short HEAD') ?? 'none',
  dirty: git('status --porcelain') ? true : false,
  uiFixesPresent: FIX_MARKERS.length - missing.length,
  uiFixesTotal: FIX_MARKERS.length,
  uiFixesMissing: missing,
  builtAt: new Date().toISOString(),
};

const banner = `// GENERATED by scripts/write-build-info.mjs - do not edit by hand.
// Rewritten on every \`pnpm start\` / \`pnpm dev\`.
`;

writeFileSync(
  resolve(appRoot, 'constants/buildInfo.ts'),
  `${banner}
export const BUILD_INFO = ${JSON.stringify(info, null, 2)} as const;

export type BuildInfo = typeof BUILD_INFO;
`,
  'utf8',
);

console.log(
  `[build-info] ${info.tree} @ ${info.branch}#${info.commit}${info.dirty ? '*' : ''} ` +
    `- UI fixes ${info.uiFixesPresent}/${info.uiFixesTotal}` +
    (missing.length ? ` (missing: ${missing.join(', ')})` : ''),
);
